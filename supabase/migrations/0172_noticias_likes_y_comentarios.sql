-- 0172 — Likes y comentarios en publicaciones del club (noticias_feed)
-- Producción: un like por jugador, comentarios con autor, RLS + WITH CHECK,
-- club_id en ambas tablas, conteos en la noticia (sin inflar el feed).

ALTER TABLE public.noticias_feed
  ADD COLUMN IF NOT EXISTS likes_count INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS comments_count INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS public.noticias_likes (
  id              BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  club_id         BIGINT NOT NULL REFERENCES public.clubes(id) ON DELETE CASCADE,
  noticia_id      BIGINT NOT NULL REFERENCES public.noticias_feed(id) ON DELETE CASCADE,
  jugador_app_id  UUID NOT NULL REFERENCES public.jugadores_app(id) ON DELETE CASCADE,
  creado_en       TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (noticia_id, jugador_app_id)
);

CREATE INDEX IF NOT EXISTS idx_noticias_likes_noticia
  ON public.noticias_likes (noticia_id);

CREATE TABLE IF NOT EXISTS public.noticias_comentarios (
  id              BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  club_id         BIGINT NOT NULL REFERENCES public.clubes(id) ON DELETE CASCADE,
  noticia_id      BIGINT NOT NULL REFERENCES public.noticias_feed(id) ON DELETE CASCADE,
  jugador_app_id  UUID NOT NULL REFERENCES public.jugadores_app(id) ON DELETE CASCADE,
  cuerpo          TEXT NOT NULL,
  activo          BOOLEAN NOT NULL DEFAULT TRUE,
  creado_en       TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT noticias_comentarios_cuerpo_len
    CHECK (char_length(btrim(cuerpo)) BETWEEN 1 AND 400)
);

CREATE INDEX IF NOT EXISTS idx_noticias_comentarios_noticia
  ON public.noticias_comentarios (noticia_id, creado_en)
  WHERE activo = TRUE;

ALTER TABLE public.noticias_likes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.noticias_comentarios ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.current_jugador_app_id()
RETURNS UUID
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT id
  FROM public.jugadores_app
  WHERE auth_user_id = auth.uid()
    AND activo = TRUE
  LIMIT 1;
$$;

REVOKE ALL ON FUNCTION public.current_jugador_app_id() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.current_jugador_app_id() TO authenticated;

-- Lectura pública (perfil del club + feed)
CREATE POLICY noticias_likes_select
  ON public.noticias_likes FOR SELECT
  USING (TRUE);

CREATE POLICY noticias_likes_insert
  ON public.noticias_likes FOR INSERT
  TO authenticated
  WITH CHECK (
    jugador_app_id = public.current_jugador_app_id()
    AND club_id = (SELECT n.club_id FROM public.noticias_feed n WHERE n.id = noticia_id)
  );

CREATE POLICY noticias_likes_delete
  ON public.noticias_likes FOR DELETE
  TO authenticated
  USING (jugador_app_id = public.current_jugador_app_id());

CREATE POLICY noticias_comentarios_select
  ON public.noticias_comentarios FOR SELECT
  USING (activo = TRUE);

CREATE POLICY noticias_comentarios_insert
  ON public.noticias_comentarios FOR INSERT
  TO authenticated
  WITH CHECK (
    jugador_app_id = public.current_jugador_app_id()
    AND activo = TRUE
    AND club_id = (SELECT n.club_id FROM public.noticias_feed n WHERE n.id = noticia_id)
  );

CREATE POLICY noticias_comentarios_update_own
  ON public.noticias_comentarios FOR UPDATE
  TO authenticated
  USING (jugador_app_id = public.current_jugador_app_id())
  WITH CHECK (jugador_app_id = public.current_jugador_app_id());

GRANT SELECT ON public.noticias_likes TO anon, authenticated;
GRANT SELECT, INSERT, DELETE ON public.noticias_likes TO authenticated;
GRANT SELECT ON public.noticias_comentarios TO anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.noticias_comentarios TO authenticated;

CREATE OR REPLACE FUNCTION public.fn_toggle_noticia_like(p_noticia_id BIGINT)
RETURNS TABLE (liked BOOLEAN, likes_count INTEGER)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_jugador UUID;
  v_club_id BIGINT;
  v_liked BOOLEAN;
  v_count INTEGER;
BEGIN
  v_jugador := public.current_jugador_app_id();
  IF v_jugador IS NULL THEN
    RAISE EXCEPTION 'Tenés que ingresar como jugador para dar me gusta';
  END IF;

  SELECT n.club_id INTO v_club_id
  FROM public.noticias_feed n
  WHERE n.id = p_noticia_id AND n.activo = TRUE;
  IF v_club_id IS NULL THEN
    RAISE EXCEPTION 'Publicación no disponible';
  END IF;

  IF EXISTS (
    SELECT 1 FROM public.noticias_likes
    WHERE noticia_id = p_noticia_id AND jugador_app_id = v_jugador
  ) THEN
    DELETE FROM public.noticias_likes
    WHERE noticia_id = p_noticia_id AND jugador_app_id = v_jugador;
    v_liked := FALSE;
  ELSE
    INSERT INTO public.noticias_likes (club_id, noticia_id, jugador_app_id)
    VALUES (v_club_id, p_noticia_id, v_jugador);
    v_liked := TRUE;
  END IF;

  SELECT COUNT(*)::INTEGER INTO v_count
  FROM public.noticias_likes
  WHERE noticia_id = p_noticia_id;

  UPDATE public.noticias_feed
  SET likes_count = v_count
  WHERE id = p_noticia_id;

  liked := v_liked;
  likes_count := v_count;
  RETURN NEXT;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_comentar_noticia(p_noticia_id BIGINT, p_cuerpo TEXT)
RETURNS TABLE (
  id BIGINT,
  cuerpo TEXT,
  creado_en TIMESTAMPTZ,
  autor_nombre TEXT,
  autor_foto TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_jugador UUID;
  v_club_id BIGINT;
  v_cuerpo TEXT;
  v_id BIGINT;
BEGIN
  v_jugador := public.current_jugador_app_id();
  IF v_jugador IS NULL THEN
    RAISE EXCEPTION 'Tenés que ingresar como jugador para comentar';
  END IF;

  v_cuerpo := btrim(p_cuerpo);
  IF char_length(v_cuerpo) < 1 OR char_length(v_cuerpo) > 400 THEN
    RAISE EXCEPTION 'El comentario debe tener entre 1 y 400 caracteres';
  END IF;

  SELECT n.club_id INTO v_club_id
  FROM public.noticias_feed n
  WHERE n.id = p_noticia_id AND n.activo = TRUE;
  IF v_club_id IS NULL THEN
    RAISE EXCEPTION 'Publicación no disponible';
  END IF;

  INSERT INTO public.noticias_comentarios (club_id, noticia_id, jugador_app_id, cuerpo)
  VALUES (v_club_id, p_noticia_id, v_jugador, v_cuerpo)
  RETURNING noticias_comentarios.id INTO v_id;

  UPDATE public.noticias_feed
  SET comments_count = (
    SELECT COUNT(*)::INTEGER
    FROM public.noticias_comentarios
    WHERE noticia_id = p_noticia_id AND activo = TRUE
  )
  WHERE noticias_feed.id = p_noticia_id;

  RETURN QUERY
  SELECT
    c.id,
    c.cuerpo,
    c.creado_en,
    ja.nombre_display,
    ja.foto_url
  FROM public.noticias_comentarios c
  JOIN public.jugadores_app ja ON ja.id = c.jugador_app_id
  WHERE c.id = v_id;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_toggle_noticia_like(BIGINT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.fn_comentar_noticia(BIGINT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fn_toggle_noticia_like(BIGINT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.fn_comentar_noticia(BIGINT, TEXT) TO authenticated;
